// Precompiles src/lib/model/work-trace.schema.json into a standalone validator so the
// shipped library never calls `new Function` (works under strict CSP, no Ajv compiler in bundle).
// Run: node scripts/gen-validator.mjs   (also runs before check/build)
import { readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schema = JSON.parse(readFileSync('src/lib/model/work-trace.schema.json', 'utf8'));
const ajv = new Ajv2020({
	allErrors: true,
	strict: true,
	allowUnionTypes: true,
	strictRequired: false,
	code: { source: true, esm: true }
});
// RFC 3339 date-time (the schema's `format: date-time`).
ajv.addFormat('date-time', /^\d{4}-\d{2}-\d{2}[Tt]\d{2}:\d{2}:\d{2}(?:\.\d+)?(?:[Zz]|[+-]\d{2}:\d{2})$/);
let code = standaloneCode(ajv, ajv.compile(schema));
// Ajv emits a CommonJS require for its string-length helper even in ESM mode; inline it
// (Unicode code point count, same semantics) so the output has no runtime dependency.
code = code.replace(
	/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g,
	'((s) => { let n = 0; for (const _ of s) n++; return n; })'
);
if (/require\(|new Function|eval\(/.test(code)) throw new Error('standalone validator is not self-contained');
writeFileSync(
	'src/lib/model/schema-validator.generated.js',
	'// @ts-nocheck\n// GENERATED by scripts/gen-validator.mjs from work-trace.schema.json. Do not edit.\n' + code
);
